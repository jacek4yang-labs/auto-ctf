// CRC-32 (IEEE 802.3, reflected) — zip entries and CRC32-collision attacks.

fn crc32_table() -> &'static [u32; 256] {
    use std::sync::OnceLock;
    static TABLE: OnceLock<[u32; 256]> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut table = [0u32; 256];
        for (i, entry) in table.iter_mut().enumerate() {
            let mut c = i as u32;
            for _ in 0..8 {
                c = if c & 1 != 0 { 0xedb8_8320 ^ (c >> 1) } else { c >> 1 };
            }
            *entry = c;
        }
        table
    })
}

/// Streaming CRC-32 state (init with 0xFFFFFFFF, finalize with !state).
pub struct Crc32 {
    state: u32,
}

impl Crc32 {
    pub fn new() -> Self {
        Self { state: 0xFFFF_FFFF }
    }

    pub fn update(&mut self, data: &[u8]) {
        let table = crc32_table();
        for &b in data {
            self.state = table[((self.state ^ b as u32) & 0xff) as usize] ^ (self.state >> 8);
        }
    }

    pub fn finalize(self) -> u32 {
        !self.state
    }
}

/// One-shot CRC-32.
pub fn crc32(data: &[u8]) -> u32 {
    let mut c = Crc32::new();
    c.update(data);
    c.finalize()
}

/// CRC-32 stepping primitive for ZipCrypto key updates.
pub fn crc32_step(prev: u32, byte: u8) -> u32 {
    let table = crc32_table();
    table[((prev ^ byte as u32) & 0xff) as usize] ^ (prev >> 8)
}

#[cfg(test)]
mod md5_tests {
    use super::*;

    #[test]
    fn crc32_standard_vector() {
        // ISO-HDLC check value for "123456789"
        assert_eq!(crc32(b"123456789"), 0xcbf4_3926);
        assert_eq!(crc32(b""), 0);
        // step primitive matches the streaming intermediate state
        let mut st = Crc32::new();
        st.update(b"a");
        assert_eq!(st.finalize(), crc32(b"a"));
        assert_eq!(crc32_step(0xFFFF_FFFF, b'a'), !crc32(b"a"));
    }

    #[test]
    fn rfc1321_vectors() {
        assert_eq!(hex_encode(&md5(b"")), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(hex_encode(&md5(b"a")), "0cc175b9c0f1b6a831c399e269772661");
        assert_eq!(hex_encode(&md5(b"abc")), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(
            hex_encode(&md5(b"message digest")),
            "f96b697d7cb7938d525a2f31aaf161d0"
        );
        assert_eq!(
            hex_encode(&md5(b"abcdefghijklmnopqrstuvwxyz")),
            "c3fcd3d76192e4007dfb496cca67e13b"
        );
    }
}
